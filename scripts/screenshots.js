// Takes the App Center screenshots of the built-in apps: `npm run build && npm run screenshots`.
// Starts `vite preview`, opens each app on a clean profile with a little sample content and
// saves its window as src/apps/<folder>/screenshots/main.jpg (plus an index.js listing it).
// Commit the output; the App Center bundles it.
import { spawn } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { chromium } from '@playwright/test';

const PORT = 4179;
const BASE = `http://localhost:${PORT}`;
const APPS_DIR = new URL('../src/apps/', import.meta.url);

/** @typedef {import('playwright').Page} Page */

/** App folder → how to open it and what to show. */
const APPS = {
  files: { name: 'File Explorer', setup: setupFiles },
  terminal: { name: 'Terminal', setup: setupTerminal },
  editor: { name: 'Nexus Edit', setup: setupEditor },
  settings: { name: 'Settings', setup: async () => {} },
  monitor: { name: 'System Monitor', setup: setupMonitor },
  appcenter: { name: 'App Center', setup: async () => {} },
  help: { name: 'Help', setup: async () => {} },
  welcome: { name: 'Welcome', setup: async () => {} },
};

const preview = spawn(`npx vite preview --port ${PORT} --strictPort`, { shell: true, stdio: 'ignore' });
try {
  await waitForServer();
  const browser = await chromium.launch();
  for (const [folder, app] of Object.entries(APPS)) {
    const page = await browser.newPage({ viewport: { width: 1280, height: 800 }, colorScheme: 'dark' });
    await cleanProfile(page);
    if (folder !== 'welcome') await page.keyboard.press('Escape');
    if (folder !== 'welcome') await openApp(page, app.name);
    await app.setup(page);
    await page.waitForTimeout(800);
    const shot = await page.locator('.nx-windows .nx-window.is-focused').screenshot({ type: 'jpeg', quality: 72 });
    const dir = new URL(`${folder}/screenshots/`, APPS_DIR);
    mkdirSync(dir, { recursive: true });
    writeFileSync(new URL('main.jpg', dir), shot);
    writeFileSync(
      new URL('index.js', dir),
      "// Generated by scripts/screenshots.js.\nimport main from './main.jpg';\n\nexport default [main];\n",
    );
    console.log(`${folder}: ${Math.round(shot.length / 1024)} KB`);
    await page.close();
  }
  await browser.close();
} finally {
  preview.kill();
}

async function waitForServer() {
  for (let i = 0; i < 60; i++) {
    try {
      if ((await fetch(BASE)).ok) return;
    } catch {
      // not up yet
    }
    await new Promise((r) => setTimeout(r, 500));
  }
  throw new Error('vite preview did not start (did you run npm run build?)');
}

/** @param {Page} page */
async function cleanProfile(page) {
  await page.goto(`${BASE}/icons/icon.svg`);
  await page.evaluate(async () => {
    localStorage.clear();
    for (const { name } of (await indexedDB.databases?.()) ?? [])
      await new Promise((done) => {
        const request = indexedDB.deleteDatabase(/** @type {string} */ (name));
        request.onsuccess = request.onerror = request.onblocked = done;
      });
  });
  await page.goto(BASE);
  await page.waitForSelector('html[data-kernel="ready"]', { timeout: 30_000 });
  await page.waitForFunction(() => !document.querySelector('.nx-boot'), null, { timeout: 15_000 });
}

/** @param {Page} page @param {string} name */
async function openApp(page, name) {
  await page.keyboard.press('Control+k');
  await page.keyboard.type(name);
  await page
    .getByRole('option', { name: new RegExp(`^${name}`) })
    .first()
    .waitFor();
  await page.keyboard.press('Enter');
  await page.locator('.nx-windows .nx-window.is-focused').waitFor();
}

/** @param {Page} page */
async function setupFiles(page) {
  const files = page.locator('.nx-windows [data-testid="files"]');
  await files.locator('[data-testid="files-place"][data-location$="/Documents"]').click();
  await files.locator('input[type=file]').setInputFiles([
    {
      name: 'Project plan.md',
      mimeType: 'text/markdown',
      buffer: Buffer.from('# Project plan\n\n- Design\n- **Build**\n- Ship'),
    },
    { name: 'budget.csv', mimeType: 'text/csv', buffer: Buffer.from('month,amount\nJan,120\nFeb,95\n') },
    { name: 'app.js', mimeType: 'text/javascript', buffer: Buffer.from('export const answer = 42;\n') },
    { name: 'notes.txt', mimeType: 'text/plain', buffer: Buffer.from('Remember the milk.') },
  ]);
  await page.keyboard.press('Escape');
  await files
    .locator('.nx-files-toolbar > .nx-icon-btn[aria-pressed]')
    .last()
    .click()
    .catch(() => {});
  await files.locator('.nx-files-item', { hasText: 'Project plan.md' }).click();
}

/** @param {Page} page */
async function setupTerminal(page) {
  const input = page.locator('.nx-windows [data-testid="term-input"]');
  for (const line of ['nexusfetch', 'ls -la ~']) {
    await input.fill(line);
    await input.press('Enter');
    await page.waitForTimeout(300);
  }
}

/** @param {Page} page */
async function setupEditor(page) {
  await page.locator('.nx-windows .cm-content').click();
  await page.keyboard.type(
    "// Nexus Edit\nexport function greet(name) {\n  const time = new Date().getHours();\n  return `Good ${time < 12 ? 'morning' : 'day'}, ${name}!`;\n}\n",
    { delay: 0 },
  );
}

/** @param {Page} page */
async function setupMonitor(page) {
  await page.keyboard.press('Control+Alt+t');
  await page.waitForTimeout(500);
  await openApp(page, 'System Monitor');
  // CPU needs two samples (one second apart).
  await page.waitForTimeout(2500);
}
